using System.Runtime.Versioning;
using Microsoft.Extensions.Logging;
using Parlotype.Core.Settings;
using Parlotype.Core.TextInjection;
using Parlotype.Platform.MacOs;
using SharpHook;
using SharpHook.Data;

namespace Parlotype.Platform.TextInjection;

/// <summary>
/// Injects text on macOS via pasteboard-with-restore: saves the current
/// pasteboard text, sets the transcribed text, simulates Cmd+V, then restores
/// the original content (ADR-077). The macOS counterpart of
/// <see cref="ClipboardTextInjectionService"/>.
/// </summary>
/// <remarks>
/// <para>
/// Posting the keystroke requires the Accessibility permission, and a user can
/// dictate without it: the record button on the widget needs no hotkey. In
/// that state the paste cannot happen, and restoring the clipboard afterwards
/// would throw the dictation away with nothing on screen to say so. So when the
/// permission is missing, or the keystroke is refused, the text is
/// <b>left on the pasteboard</b> as an ordinary copy and
/// <see cref="TextInjectionNotPermittedException"/> tells the caller, which
/// explains it to the user.
/// </para>
/// </remarks>
[SupportedOSPlatform("macos")]
public sealed class MacOsClipboardTextInjectionService : ITextInjectionService
{
    /// <summary><c>NSPasteboardTypeString</c>.</summary>
    private const string PlainTextType = "public.utf8-plain-text";

    /// <summary>
    /// The nspasteboard.org markers clipboard managers honour: this content is
    /// transient and machine-generated, so do not record it in history. The
    /// macOS equivalent of the Windows clipboard exclusion formats. Restoring
    /// the user's own content deliberately sets none of them.
    /// </summary>
    private static readonly string[] TransientMarkerTypes =
    [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
    ];

    private readonly ITargetWindowTracker _windowTracker;
    private readonly ISystemPermissionService _permissions;
    private readonly ILogger<MacOsClipboardTextInjectionService> _logger;

    // The pasteboard and the keystroke, as seams: a test must be able to drive
    // this class without overwriting the developer's clipboard or typing Cmd+V
    // into whatever window happens to be in front.
    private readonly Func<string?> _getPasteboardText;
    private readonly Action<string, bool> _setPasteboardText;
    private readonly Action _clearPasteboard;
    private readonly Func<bool> _postPasteShortcut;

    public MacOsClipboardTextInjectionService(
        ITargetWindowTracker windowTracker,
        ISystemPermissionService permissions,
        ILogger<MacOsClipboardTextInjectionService> logger)
        : this(windowTracker, permissions, logger,
            GetPasteboardText, SetPasteboardText, ClearPasteboard, postPasteShortcut: null)
    {
        MacOsNative.EnsureFrameworkLoaded("AppKit");
    }

    internal MacOsClipboardTextInjectionService(
        ITargetWindowTracker windowTracker,
        ISystemPermissionService permissions,
        ILogger<MacOsClipboardTextInjectionService> logger,
        Func<string?> getPasteboardText,
        Action<string, bool> setPasteboardText,
        Action clearPasteboard,
        Func<bool>? postPasteShortcut)
    {
        _windowTracker = windowTracker;
        _permissions = permissions;
        _logger = logger;
        _getPasteboardText = getPasteboardText;
        _setPasteboardText = setPasteboardText;
        _clearPasteboard = clearPasteboard;
        _postPasteShortcut = postPasteShortcut ?? PostCommandV;
    }

    public async Task InjectTextAsync(string text, CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrEmpty(text))
            return;

        // Asked every time, not once: the user can grant or withdraw it while
        // the app runs, and the answer costs one system call.
        if (_permissions.GetState(SystemPermission.Accessibility) != SystemPermissionState.Granted)
        {
            LeaveOnPasteboard(text);
            throw new TextInjectionNotPermittedException();
        }

        var previousClipboard = _getPasteboardText();
        var pasted = false;

        try
        {
            _setPasteboardText(text, true);

            _windowTracker.ActivateTargetWindow();
            await Task.Delay(50, cancellationToken);

            pasted = _postPasteShortcut();

            // Give the target app time to process the paste
            if (pasted)
                await Task.Delay(150, cancellationToken);
        }
        finally
        {
            // Only a paste that was actually posted may be followed by a
            // restore. After a refused one the dictated text is the only copy.
            if (pasted)
                RestorePasteboard(previousClipboard);
        }

        if (!pasted)
        {
            // The permission read as granted and the keystroke was refused all
            // the same (a stale grant after a rebuild does this).
            LeaveOnPasteboard(text);
            throw new TextInjectionNotPermittedException();
        }

        _logger.LogDebug("Injected {Length} characters via pasteboard paste", text.Length);
    }

    /// <summary>
    /// Puts the text on the pasteboard as an ordinary copy, without the
    /// transient markers: this time it is meant to stay, and to be found.
    /// </summary>
    private void LeaveOnPasteboard(string text)
    {
        _setPasteboardText(text, false);
        _logger.LogWarning(
            "Pasting is not permitted (Accessibility) — left {Length} characters on the pasteboard instead",
            text.Length);
    }

    private readonly EventSimulator _simulator = new();

    /// <summary>Posts Cmd+V. False when macOS refused any part of it.</summary>
    private bool PostCommandV()
    {
        var posted = Report(_simulator.SimulateKeyPress(KeyCode.VcLeftMeta), "SimulateKeyPress(Cmd)");
        posted &= Report(_simulator.SimulateKeyPress(KeyCode.VcV), "SimulateKeyPress(V)");
        posted &= Report(_simulator.SimulateKeyRelease(KeyCode.VcV), "SimulateKeyRelease(V)");
        // Always released, even after a failure above: a Command key left
        // "down" would turn the user's next keystrokes into shortcuts.
        posted &= Report(_simulator.SimulateKeyRelease(KeyCode.VcLeftMeta), "SimulateKeyRelease(Cmd)");
        return posted;
    }

    private bool Report(UioHookResult result, string step)
    {
        if (result == UioHookResult.Success)
            return true;

        _logger.LogWarning("{Step} failed: {Result}", step, result);
        return false;
    }

    private void RestorePasteboard(string? previousContent)
    {
        try
        {
            if (previousContent is not null)
                _setPasteboardText(previousContent, false);
            else
                _clearPasteboard();
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Failed to restore pasteboard contents");
        }
    }

    // --- NSPasteboard interop ---

    private static nint GeneralPasteboard() =>
        MacOsNative.Send(MacOsNative.Class("NSPasteboard"), MacOsNative.Selector("generalPasteboard"));

    private static string? GetPasteboardText()
    {
        using var pool = MacOsNative.AutoreleasePool.Create();

        var type = MacOsNative.CreateString(PlainTextType);
        try
        {
            var value = MacOsNative.Send(GeneralPasteboard(), MacOsNative.Selector("stringForType:"), type);
            return MacOsNative.ReadString(value);
        }
        finally
        {
            MacOsNative.CFRelease(type);
        }
    }

    private static void SetPasteboardText(string text, bool transient)
    {
        using var pool = MacOsNative.AutoreleasePool.Create();

        var pasteboard = GeneralPasteboard();
        if (pasteboard == 0)
            throw new InvalidOperationException("Cannot open the pasteboard");

        MacOsNative.Send(pasteboard, MacOsNative.Selector("clearContents"));

        if (!SetString(pasteboard, text, PlainTextType))
            throw new InvalidOperationException("Could not write to the pasteboard");

        if (!transient)
            return;

        // Best effort, like the Windows exclusion formats: a marker that fails
        // to set never blocks the paste.
        foreach (var marker in TransientMarkerTypes)
            SetString(pasteboard, string.Empty, marker);
    }

    private static bool SetString(nint pasteboard, string value, string type)
    {
        var nativeValue = MacOsNative.CreateString(value);
        var nativeType = MacOsNative.CreateString(type);
        try
        {
            return MacOsNative.AsBool(MacOsNative.Send(
                pasteboard, MacOsNative.Selector("setString:forType:"), nativeValue, nativeType));
        }
        finally
        {
            MacOsNative.CFRelease(nativeType);
            MacOsNative.CFRelease(nativeValue);
        }
    }

    private static void ClearPasteboard()
    {
        using var pool = MacOsNative.AutoreleasePool.Create();
        MacOsNative.Send(GeneralPasteboard(), MacOsNative.Selector("clearContents"));
    }
}
